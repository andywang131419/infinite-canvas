export type Position = {
    x: number;
    y: number;
};

export type ViewportTransform = {
    x: number;
    y: number;
    k: number;
};

export enum CanvasNodeType {
    Image = "image",
    Text = "text",
    Config = "config",
    Video = "video",
    Audio = "audio",
    Group = "group",
}

// Node types are open strings: built-ins use CanvasNodeType and plugins use "<pluginId>:<name>".
export type CanvasNodeTypeId = CanvasNodeType | (string & {});

export type CanvasNodeStatus = "idle" | "success" | "loading" | "error";
export type CanvasGenerationMode = "text" | "image" | "video" | "audio";
export type CanvasImageGenerationType = "generation" | "edit";

export type CanvasNodeImage = {
    id: string;
    status: CanvasNodeStatus;
    errorDetails?: string;
    content: string;
    storageKey?: string;
    naturalWidth: number;
    naturalHeight: number;
    bytes: number;
    mimeType: string;
    /**
     * 服务端任务 id（T04-B）。粒度是**每张图一个 job**：一次"生成 4 张"有 4 个
     * imageId，其中 2 张失败时要能单独重试，所以 jobId 挂在**图**上而不是节点上。
     * 刷新后靠它把结果写回正确的那张图。
     */
    jobId?: string;
};

export type CanvasNodeText = {
    id: string;
    status: CanvasNodeStatus;
    errorDetails?: string;
    content: string;
};

export type CanvasNodeMetadata = {
    content?: string;
    composerContent?: string;
    prompt?: string;
    status?: CanvasNodeStatus;
    errorDetails?: string;
    fontSize?: number;
    generationMode?: CanvasGenerationMode;
    generationType?: CanvasImageGenerationType;
    model?: string;
    reasoningEffort?: "auto" | "low" | "medium" | "high" | "xhigh";
    size?: string;
    quality?: string;
    background?: string;
    count?: number;
    textCount?: number;
    texts?: CanvasNodeText[];
    primaryTextId?: string;
    seconds?: string;
    vquality?: string;
    generateAudio?: string;
    watermark?: string;
    videoMode?: string;
    audioVoice?: string;
    audioFormat?: string;
    audioSpeed?: string;
    audioInstructions?: string;
    references?: string[];
    naturalWidth?: number;
    naturalHeight?: number;
    freeResize?: boolean;
    images?: CanvasNodeImage[];
    primaryImageId?: string;
    storageKey?: string;
    mimeType?: string;
    bytes?: number;
    durationMs?: number;
    /**
     * 服务端任务 id（T04-B）。
     *
     * 一次生成 N 张图时，真正的 jobId 记在每张图的 `images[].jobId` 上
     * （见 `CanvasNodeImage.jobId`）；这里存的是本节点最近一次提交的任务，
     * 用于"停止生成"时精确取消、以及快速判断这个节点有没有在跑的活。
     */
    jobId?: string;
    /**
     * 幂等键种子（T04-B 阶段 2）。
     *
     * 音频/视频节点一次只出一个结果，没有 `images[].id` 那样的子项 id 可用，
     * 所以每次生成动作另起一个种子，组成 `${nodeId}:${jobKey}`。
     * **不能只用 nodeId**：服务端幂等不看任务是否已终态，只用 nodeId 会让
     * "重新生成"拿回上一次已完成的 job，用户以为重生成了、出来的还是旧的。
     */
    jobKey?: string;
    groupId?: string;
    interactive?: boolean; // Plugin node interaction/move state; see CanvasNodeDefinition.interactionToggle.
};

