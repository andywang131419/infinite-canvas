-- 备份审计行增加 `uploaded` 列：这次备份**到底有没有传到远端**。
--
-- 为什么不改 0001/0002：迁移执行器（src/db/client.ts）对每个文件做 sha256
-- checksum 校验，已执行过的迁移内容一旦变化就**拒绝启动**。只能新增迁移。
--
-- 背景（QA R2 之后发现的同类第 3 例「审计说谎」）：
--   server 镜像是 `oven/bun`，里面**没有 rclone**（异地上传统一由 backup 容器负责，
--   不给 server 装是刻意的分工）。而 `uploadWithRclone` 在 ENOENT 时返回 false
--   且不算失败 —— 这个设计是对的：本地至少有一份，不该因为缺个可选二进制就把
--   整次备份判死。问题是审计行照样写 `target='remote:dest'` + status='success'，
--   看的人以为数据上了远端，实际只躺在本地 stage 目录。
--
--   与 P1-R2-5 的 `media_expected` 是同一条原则：审计行必须自解释，
--   不能让人翻 docker logs 才能发现"其实没传"。
--
-- 三态（NULL 不是"未知"，是"不适用"）：
--   NULL = 没配远端 / 还没轮到上传（running 行）
--   1    = 已确认传到远端
--   0    = 配了远端但没传成（含镜像里没装 rclone）
--
-- 注意这列**不能替代** target 的降级：人工标签 BACKUP_TARGET_LABEL 场景下
-- target 是运维自己写的字符串，看它判断不出有没有真上传，只有这列能说明真相。
-- -----------------------------------------------------------------------------

ALTER TABLE backups ADD COLUMN uploaded INTEGER;
